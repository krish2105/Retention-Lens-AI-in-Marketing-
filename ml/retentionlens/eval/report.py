"""Render a run's metrics as a Markdown report (numbers only from metrics.json)."""
from __future__ import annotations


def _table(results: dict, kind: str, metric: str, digits: int = 3) -> list[str]:
    cutoffs = list(results["cutoffs"])
    header = "| Model | " + " | ".join(f"{c} ({results['cutoffs'][c]['role']})" for c in cutoffs) + " |"
    rows = [header, "|---|" + "---|" * len(cutoffs)]
    for model in results["cutoffs"][cutoffs[0]][kind]:
        cells = [f"{results['cutoffs'][c][kind][model][metric]:.{digits}f}" for c in cutoffs]
        rows.append(f"| `{model}` | " + " | ".join(cells) + " |")
    return rows


def render_report(results: dict) -> str:
    cutoffs = results["cutoffs"]
    out = [
        "# Model results — 90-day lapse and value",
        "",
        f"Run `{results['run_id']}` · data SHA-256 `{results['data_sha256'][:16]}…` · seed {results['seed']} · horizon {results['horizon_days']} days.",
        "Generated by `uv run python -m retentionlens.cli models`; every number is read from the run's `metrics.json`.",
        "",
        "## Population per cutoff",
        "",
        "| Cutoff | Role | Customers scored | Training rows | Lapse rate |",
        "|---|---|---|---|---|",
        *[
            f"| {c} | {s['role']} | {s['n_customers']} | {s['n_train_rows']} | {s['lapse']['lightgbm']['base_rate']:.3f} |"
            for c, s in cutoffs.items()
        ],
        "",
        "## Lapse: PR-AUC (higher is better; positive class = no purchase in 90 days)",
        "",
        *_table(results, "lapse", "pr_auc"),
        "",
        "## Lapse: ROC-AUC",
        "",
        *_table(results, "lapse", "roc_auc"),
        "",
        "## Lapse: Brier score (lower is better; measures calibration and sharpness)",
        "",
        *_table(results, "lapse", "brier", 4),
        "",
        "## Lapse: lift in the top 10% of predicted risk",
        "",
        *_table(results, "lapse", "top_lift", 2),
        "",
        "## Value: normalised Gini (ranking of 90-day spend; 1 = perfect)",
        "",
        *_table(results, "value", "normalized_gini"),
        "",
        "## Value: mean absolute error (£ per customer, lower is better)",
        "",
        *_table(results, "value", "mae", 1),
        "",
        "## Does LightGBM beat each baseline? (claim needs ≥3 of 4 cutoffs)",
        "",
        "| Comparison | Baseline | LightGBM wins |",
        "|---|---|---|",
    ]
    for comparison, baselines in results["comparison"].items():
        for baseline, score in baselines.items():
            out.append(f"| {comparison} | `{baseline}` | {score['wins']} of {score['of']} |")
    out += ["", "Library versions: " + ", ".join(f"{k} {v}" for k, v in results["versions"].items()), ""]
    return "\n".join(out)
