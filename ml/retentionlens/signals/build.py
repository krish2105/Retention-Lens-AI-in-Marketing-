"""Serving builder for the Signals page (outcome B)."""
from __future__ import annotations

import json
from datetime import date
from pathlib import Path

import pandas as pd

from ..data.profile import upsert_register
from .network import co_purchase_graph, network_payload
from .scrape import scrape
from .social import social_signals
from .web import web_signals


def build_signals(prepared: pd.DataFrame, scored: pd.DataFrame, out: Path):
    repo = out.parents[1]
    cache = repo / "data" / "raw" / "signals"
    try:
        competitor = scrape(cache)
    except OSError as error:
        competitor = {"available": False, "error": str(error)}
    top_names = prepared[prepared["is_sale"]]["description"].dropna().value_counts().head(60).index.tolist()
    payload = {
        "web": web_signals(prepared, cache),
        "network": network_payload(co_purchase_graph(prepared)),
        "social": social_signals(top_names),
        "competitor": competitor,
    }
    (out / "signals.json").write_text(json.dumps(payload, separators=(",", ":")))
    register = repo / "project" / "DATA_SOURCE_REGISTER.csv"
    today = date.today().isoformat()
    upsert_register(register, {"name": "wikimedia_pageviews", "url": "https://wikimedia.org/api/rest_v1/", "version": "per-article monthly 2016-01..2025-12",
                               "access_date": today, "license": "CC0", "sha256": "", "allowed_use": "Any use; cached locally, not committed",
                               "notes": "Articles: Christmas_decoration, Candle, Tote_bag, Mug. Seasonal shape only."})
    upsert_register(register, {"name": "books_toscrape_sandbox", "url": "https://books.toscrape.com/", "version": "catalogue pages 1-3",
                               "access_date": today, "license": "Sandbox site built for scraping practice", "sha256": "", "allowed_use": "Teaching demo only",
                               "notes": "robots.txt checked; polite delay; cached locally"})
    upsert_register(register, {"name": "synthetic_social_posts", "url": "generated by ml/retentionlens/signals/social.py", "version": "seed 42, 600 posts",
                               "access_date": today, "license": "Own synthetic data", "sha256": "", "allowed_use": "Demonstration only; labelled SYNTHETIC",
                               "notes": "Not evidence of real customer sentiment"})
    return None
